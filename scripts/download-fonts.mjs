import { mkdir, access, writeFile } from "node:fs/promises";
import { constants } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const FONT_DIR = path.join(ROOT, "src", "assets", "fonts");
const CSS_OUT = path.join(ROOT, "src", "fonts.css");

const FONT_UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";

const SUBSETS = new Set(["latin", "latin-ext"]);

// Google Fonts serves variable WOFF2 files: one file per subset covers the
// whole requested weight range, so we emit a single @font-face per subset.
const FAMILIES = [
  { family: "Lora", weights: [400, 500, 600, 700] },
  { family: "Roboto", weights: [400, 500, 700] },
  { family: "JetBrains Mono", weights: [400, 500, 700] },
];

const slugify = (name) =>
  name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

const exists = async (file) => {
  try {
    await access(file, constants.F_OK);
    return true;
  } catch {
    return false;
  }
};

function buildUrl() {
  const params = FAMILIES.map(
    ({ family, weights }) =>
      `family=${family.replace(/ /g, "+")}:wght@${weights.join(";")}`
  ).join("&");
  return `https://fonts.googleapis.com/css2?${params}&display=swap`;
}

function parseBlocks(css) {
  const faces = [];
  const re = /\/\* ([a-z-]+) \*\/\s*@font-face\s*{([^}]*)}/g;
  let match;
  while ((match = re.exec(css))) {
    const subset = match[1];
    const body = match[2];
    if (!SUBSETS.has(subset)) continue;

    const family = (body.match(/font-family:\s*'([^']+)'/) || [])[1];
    const style = (body.match(/font-style:\s*([a-z]+)/) || [])[1] || "normal";
    const url = (body.match(/url\((https:[^)]+)\)/) || [])[1];
    const unicodeRange = (body.match(/unicode-range:\s*([^;]+);/) || [])[1];

    if (!family || !url || !unicodeRange) continue;
    faces.push({ subset, family, style, url, unicodeRange: unicodeRange.trim() });
  }
  return faces;
}

async function main() {
  await mkdir(FONT_DIR, { recursive: true });

  const css = await (
    await fetch(buildUrl(), { headers: { "User-Agent": FONT_UA } })
  ).text();
  const faces = parseBlocks(css);

  if (faces.length === 0) {
    console.error("No font faces parsed from Google Fonts response.");
    process.exitCode = 1;
    return;
  }

  const ranges = new Map(
    FAMILIES.map(({ family, weights }) => [
      family,
      [Math.min(...weights), Math.max(...weights)],
    ])
  );

  const grouped = new Map();
  for (const face of faces) {
    const key = `${face.family}|${face.subset}|${face.style}`;
    if (!grouped.has(key)) grouped.set(key, face);
  }

  let downloaded = 0;
  let skipped = 0;
  let failed = 0;
  const rules = [];

  for (const face of grouped.values()) {
    const fileName = `${slugify(face.family)}-${face.subset}.woff2`;
    const dest = path.join(FONT_DIR, fileName);
    const localUrl = `./assets/fonts/${fileName}`;
    const [min, max] = ranges.get(face.family) ?? [400, 700];
    const weight = min === max ? `${min}` : `${min} ${max}`;

    if (await exists(dest)) {
      skipped++;
    } else {
      try {
        const res = await fetch(face.url, { headers: { "User-Agent": FONT_UA } });
        if (!res.ok) throw new Error(`HTTP ${res.status}`);
        await writeFile(dest, Buffer.from(await res.arrayBuffer()));
        console.log(`saved ${fileName}`);
        downloaded++;
      } catch (err) {
        console.error(`fail  ${fileName}: ${err.message}`);
        failed++;
        continue;
      }
    }

    rules.push(
      [
        "@font-face {",
        `  font-family: '${face.family}';`,
        `  font-style: ${face.style};`,
        `  font-weight: ${weight};`,
        "  font-display: swap;",
        `  src: url('${localUrl}') format('woff2');`,
        `  unicode-range: ${face.unicodeRange};`,
        "}",
      ].join("\n")
    );
  }

  const header =
    "/* Generated by scripts/download-fonts.mjs. Do not edit by hand. */\n" +
    "/* Self-hosted so the desktop app renders correctly offline. */\n\n";
  await writeFile(CSS_OUT, header + rules.join("\n\n") + "\n");

  console.log(
    `\n${downloaded} downloaded, ${skipped} skipped, ${failed} failed — wrote ${rules.length} @font-face rules`
  );
  if (failed > 0) process.exitCode = 1;
}

main();
